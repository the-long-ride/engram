/**
 * Render-time context: `hooks` = Engram hooks inject context for this host; `sharedGuide` = the file is also read by
 * hosts without hooks (e.g. `.agents/engram.md` for Copilot/Cline), so hook wording must hedge; `guidePath` = canonical
 * guide a pointer file references.
 */
export type RenderOptions = { hooks?: boolean; sharedGuide?: boolean; guidePath?: string; alwaysLoad?: boolean };

/** `true` = crisp hooked wording, `'shared'` = hedged hooked wording, `false` = manual load wording. */
type HookMode = boolean | 'shared';

function hookMode(options: RenderOptions): HookMode {
  if (!options.hooks) return false;
  return options.sharedGuide ? 'shared' : true;
}

export function globalSkillsetMarkdown(readMode = 'auto', profile: InstructionProfile = 'compact', options: RenderOptions = {}): string {
  const mode = readMode === 'manual' || readMode === 'off' ? false : hookMode(options);
  const startup = mode === true
    ? '- Engram hooks inject configured global memory even in workspaces that never ran `engram inject`.'
    : mode === 'shared'
      ? '- Where Engram hooks are installed they inject configured global memory; otherwise, in a new AI-agent workspace, run `engram load "<current task>"` even if it never ran `engram inject`.'
      : '- At the start of a new AI-agent workspace, run `engram load "<current task>"` even if that workspace has not run `engram inject`; Engram can load configured global memory.';
  return `${HEADER}

# Engram Global Agent Skillset

${instructionBody(readMode, profile, hookMode(options))}

## Global Startup

${startup}
- If global memory is not configured, tell the human to run \`engram inject --global-only --global-path <path>\` once. Do not initialize the current workspace just to read global memory.
`;
}

export function isGenerated(content: string, file = ''): boolean {
  return content.includes(HEADER)
    || content.includes(LINE_HEADER)
    || isLegacyEngramSkill(content, file)
    || hasWorkspaceManagedBlock(content)
    || isLegacyFullInstructionFile(content, file)
    || (content.includes('engram-mcp') && (content.includes('@the-long-ride/engram') || /"command":\s*"engram-mcp"/.test(content)))
    || (content.includes('https://opencode.ai/config.json') && content.includes('.opencode/engram.md') && content.includes('"engram-mcp"'))
    || isEngramPluginManifest(content, file);
}

/** Detect legacy full generated instruction files (AGENTS.md, CLAUDE.md etc with full compact body). */
function isLegacyFullInstructionFile(content: string, file: string): boolean {
  const instructionFiles = ['AGENTS.md', 'CLAUDE.md', 'GEMINI.md', '.cursor/rules/engram.mdc', '.clinerules', '.windsurfrules', '.windsurf/rules/engram.md'];
  const normalized = file.replace(/\\/g, '/');
  if (!instructionFiles.some((f) => normalized.endsWith(f))) return false;
  // Must have Engram header AND compact protocol markers to be considered legacy generated
  return (content.includes(HEADER) || content.includes(LINE_HEADER))
    && (content.includes('Save flow:') || content.includes('Rule memories:') || content.includes('Default agent mode: compact') || content.includes('Runtime Bootstrap'));
}

function isLegacyEngramSkill(content: string, file: string): boolean {
  const normalized = file.replace(/\\/g, '/');
  return normalized === '.agents/skills/engram/SKILL.md'
    && /^---[\s\S]*?\bname:\s*engram\b[\s\S]*?---/m.test(content)
    && /Engram\s+(?:Memory Skill|=|workspace memory|Agent Skillset)/i.test(content);
}

function isEngramPluginManifest(content: string, file: string): boolean {
  const normalized = file.replace(/\\/g, '/');
  if (!normalized.includes('plugin.json')) return false;
  try {
    const parsed = parseJsonLike<Record<string, any>>(content);
    return parsed.name === 'engram' && parsed._managedBy === 'engram';
  } catch {
    return false;
  }
}

export function renderSkillsetFile(target: SkillsetTarget, file: string, readMode = 'auto', profile: InstructionProfile = 'compact', options: RenderOptions = {}): string {
  const hooks = Boolean(options.hooks);
  if (target === 'mcp') return mcpConfig(file, options.alwaysLoad === true);
  if (target === 'opencode' && /opencode\.jsonc?$/u.test(file)) return opencodeConfig();
  const slashGuide = options.guidePath ?? slashGuidePath(file);
  if (target === 'slash' && file.endsWith('.toml')) return geminiSlashCommand(slashGuide);
  if (target === 'slash') return slashMarkdown(file.endsWith('SKILL.md') ? 'Engram Slash Skill' : 'Engram Slash Command', slashKind(file), slashGuide);
  if ((target === 'agent-skill' || target === 'antigravity') && file.endsWith('SKILL.md')) {
    // A skill is a thin pointer when its install has a canonical guide; otherwise it is the guide.
    return options.guidePath ? agentSkillPointer(options.guidePath) : agentSkillFile(readMode, hooks);
  }
  if (target === 'antigravity' && file.endsWith('.antigravityrules')) return antigravityRules(readMode, hooks);
  return skillsetMarkdown('Engram Agent Skillset', readMode, profile, hooks);
}

/** Workspace guide a slash adapter points to, by host folder. */
function slashGuidePath(file: string): string {
  const normalized = file.replace(/\\/g, '/');
  for (const host of ['.claude', '.cursor', '.gemini', '.opencode']) {
    if (normalized.startsWith(`${host}/`) || normalized.includes(`/${host}/`)) return `${host}/engram.md`;
  }
  return '.agents/engram.md';
}

