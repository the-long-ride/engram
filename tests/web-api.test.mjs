test('web upgrade review API exposes proposals, persists decisions, and gates final apply', async () => {
  const { cwd, env } = await tempWorkspace('engram-web-upgrade-review-');
  const old = { config: process.env.ENGRAM_CONFIG_DIR, global: process.env.ENGRAM_GLOBAL_DIR };
  process.env.ENGRAM_CONFIG_DIR = env.ENGRAM_CONFIG_DIR;
  process.env.ENGRAM_GLOBAL_DIR = env.ENGRAM_GLOBAL_DIR;
  try {
    await mkdir(path.join(cwd, '.agents'), { recursive: true });
    await writeFile(path.join(cwd, 'AGENTS.md'), '# Human\n\n<!-- engram:start -->\nOLD\n<!-- engram:end -->\n');
    await writeFile(path.join(cwd, '.agents', 'engram.md'), '# Human-owned custom guide\n');
    let plan = await apiUpgradePlan(cwd);
    const conflict = plan.items.find((item) => item.kind === 'skillset' && item.status === 'conflict');
    assert.ok(conflict, JSON.stringify(plan.items, null, 2));
    assert.equal(plan.review?.pendingReviewCount, 1);
    await assert.rejects(apiUpgradeApply(cwd, { fingerprint: plan.fingerprint, confirmed: true }), /requires review/i);

    const review = await apiUpgradeReview(cwd, plan.fingerprint, conflict.id);
    assert.equal(review.proposal.current, '# Human-owned custom guide\n');
    assert.notEqual(review.proposal.proposed, review.proposal.current);
    assert.equal(review.saved.state, 'pending');
    assert.equal(review.proposal.replaceable, false);
    assert.equal(review.proposal.ownership, 'unknown');
    assert.equal(review.proposal.forceMode, 'none');
    assert.equal(review.proposal.forceWarning, undefined);

    const resolved = await apiUpgradeResolve(cwd, {
      fingerprint: plan.fingerprint,
      itemId: conflict.id,
      state: 'keep-current'
    });
    assert.equal(resolved.review.pendingReviewCount, 0);
    assert.equal(resolved.saved.state, 'keep-current');

    plan = await apiUpgradePlan(cwd);
    assert.equal(plan.review?.pendingReviewCount, 0, JSON.stringify(plan.items.filter((item) => item.status === 'conflict' || item.status === 'invalid'), null, 2));
    const result = await apiUpgradeApply(cwd, { fingerprint: plan.fingerprint, confirmed: true });
    assert.equal(result.conflicts.length, 1);
    assert.equal(await readFile(path.join(cwd, '.agents', 'engram.md'), 'utf8'), '# Human-owned custom guide\n');
    const converged = await apiUpgradePlan(cwd);
    const instructionRow = converged.items.find((item) => path.resolve(item.file) === path.resolve(path.join(cwd, 'AGENTS.md')));
    assert.ok(instructionRow);
    assert.equal(instructionRow.status, 'current');
    const guideRow = converged.items.find((item) => path.resolve(item.file) === path.resolve(path.join(cwd, '.agents', 'engram.md')));
    assert.ok(guideRow);
    assert.equal(guideRow.status, 'conflict');
  } finally {
    restoreEnv('ENGRAM_CONFIG_DIR', old.config);
    restoreEnv('ENGRAM_GLOBAL_DIR', old.global);
    await rm(cwd, { recursive: true, force: true });
  }
});



test('global shared guide plus managed instruction converge in one upgrade pass across codex claude and gemini', async () => {
  const { cwd, env } = await tempWorkspace('engram-web-global-upgrade-converge-');
  const agentHome = path.join(cwd, 'agent-home');
  const agentConfigHome = path.join(cwd, 'agent-config');
  const globalEnv = { ...env, ENGRAM_AGENT_HOME: agentHome, ENGRAM_AGENT_CONFIG_HOME: agentConfigHome };
  const old = {
    config: process.env.ENGRAM_CONFIG_DIR,
    global: process.env.ENGRAM_GLOBAL_DIR,
    agentHome: process.env.ENGRAM_AGENT_HOME,
    agentConfigHome: process.env.ENGRAM_AGENT_CONFIG_HOME
  };
  process.env.ENGRAM_CONFIG_DIR = globalEnv.ENGRAM_CONFIG_DIR;
  process.env.ENGRAM_GLOBAL_DIR = globalEnv.ENGRAM_GLOBAL_DIR;
  process.env.ENGRAM_AGENT_HOME = agentHome;
  process.env.ENGRAM_AGENT_CONFIG_HOME = agentConfigHome;
  try {
    for (const target of ['codex', 'claude', 'gemini']) {
      const linked = await runEngram(cwd, globalEnv, ['link', '--global', target]);
      assert.equal(linked.code, 0, linked.stderr);
    }

    const guideFile = path.join(agentHome, '.agents', 'engram.md');
    const instructionFile = path.join(agentHome, '.codex', 'AGENTS.md');
    await writeFile(guideFile, '# User manually edited shared guide\n');
    const instruction = await readFile(instructionFile, 'utf8');
    assert.match(instruction, /Engram memory may arrive through hooks and MCP\./);
    await writeFile(instructionFile, instruction.replace('Engram memory may arrive through hooks and MCP.', 'OLD MANUAL CONTENT INSIDE ENGRAM BLOCK'));

    let plan = await apiUpgradePlan(cwd);
    const sharedRows = plan.items.filter((item) => path.resolve(item.file) === path.resolve(guideFile));
    assert.equal(sharedRows.length, 1, JSON.stringify(sharedRows, null, 2));
    const shared = sharedRows[0];
    assert.equal(shared.status, 'conflict');
    assert.equal(shared.forceMode, 'replace-file');
    assert.deepEqual(shared.agents, ['claude', 'codex', 'gemini']);
    const instructionRow = plan.items.find((item) => path.resolve(item.file) === path.resolve(instructionFile));
    assert.equal(instructionRow?.status, 'outdated');

    await apiUpgradeResolve(cwd, { fingerprint: plan.fingerprint, itemId: shared.id, state: 'force-latest' });
    plan = await apiUpgradePlan(cwd);
    assert.equal(plan.review?.pendingReviewCount, 0);
    const result = await apiUpgradeApply(cwd, { fingerprint: plan.fingerprint, confirmed: true });
    assert.equal(result.conflicts.length, 0);
    const guideBackup = `${guideFile}.engram-upgrade-0.0.28.bak`;
    assert.equal(await readFile(guideBackup, 'utf8'), '# User manually edited shared guide\n');

    const after = await apiUpgradePlan(cwd);
    for (const file of [guideFile, instructionFile]) {
      const item = after.items.find((row) => path.resolve(row.file) === path.resolve(file));
      assert.ok(item, `post-upgrade inventory missing ${file}`);
      assert.equal(item.status, 'current', `${file} remained ${item.status}: ${item.reason}`);
    }
    assert.equal(after.items.filter((item) => path.resolve(item.file) === path.resolve(guideFile)).length, 1);
  } finally {
    restoreEnv('ENGRAM_CONFIG_DIR', old.config);
    restoreEnv('ENGRAM_GLOBAL_DIR', old.global);
    restoreEnv('ENGRAM_AGENT_HOME', old.agentHome);
    restoreEnv('ENGRAM_AGENT_CONFIG_HOME', old.agentConfigHome);
    await rm(cwd, { recursive: true, force: true });
  }
});

