    assert.equal(apiPlan.fingerprint, expected.fingerprint);
    assert.deepEqual(apiPlan.items, expected.items);
    await assert.rejects(apiUpgradeApply(cwd, { fingerprint: apiPlan.fingerprint, confirmed: false }), /confirmation/i);
    await writeFile(path.join(cwd, 'AGENTS.md'), '<!-- Generated by Engram skillset installer. Edit with care. -->\n# stale\n');
    await assert.rejects(apiUpgradeApply(cwd, { fingerprint: apiPlan.fingerprint, confirmed: true }), /stale/i);
