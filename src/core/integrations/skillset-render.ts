/** Load wording: with hooks the context is injected, so the agent must not load at session start itself. */
function loadInstructions(readMode: string, hooks: HookMode): string[] {
  const hooked = hooks && readMode !== 'manual' && readMode !== 'off';
  if (hooked && hooks === 'shared') {
    // Shared guides are also read by hosts without hooks: hedge instead of forbidding a manual load.
    return [
      '- Engram hooks inject routed memory context on hosts where they are installed.',
      '- If no Engram context was injected, run `engram load "<current task>"` (or MCP `engram_load`) before working and whenever the task changes.'
    ];
  }
  if (hooked) {
    return [
      '- Engram hooks auto-inject routed memory context for this host; do not load it yourself when a session begins.',
      '- Run `engram load "<current task>"` (or MCP `engram_load`) only when the task changes and no fresh Engram context was injected.'
    ];
  }
  if (readMode === 'always') {
    return ['- Every request: run `engram load "<current request>"` or MCP `engram_load` at the start of every user turn.'];
  }
  return ['- Session start and task changes: run `engram load "<current task>"` or MCP `engram_load`; reply only `Engram loaded: X memories / Y total related memories.` unless asked for more.'];
}

/** `skill` = Claude pointer SKILL.md; `command` = a command file whose host reads `description` frontmatter; `plain` = Cursor (frontmatter unverified). */
type SlashKind = 'skill' | 'command' | 'plain';

function slashKind(file: string): SlashKind {
  const normalized = file.replace(/\\/g, '/');
  if (normalized.endsWith('SKILL.md')) return 'skill';
  return /(^|\/)\.cursor\//.test(normalized) ? 'plain' : 'command';
}

function slashMarkdown(title: string, kind: SlashKind, guidePath: string): string {
  const body = slashBody(title, guidePath);
  if (kind === 'plain') return body;
  // Without a description Claude lists the generator comment (first non-empty line) as the command's description.
  if (kind === 'command') return `---\ndescription: ${yamlString(SLASH_DESCRIPTION)}\n---\n${body}`;
  return agentSkill('engram', SLASH_DESCRIPTION, body, { whenToUse: ENGRAM_WHEN_TO_USE, userInvocable: true });
}

