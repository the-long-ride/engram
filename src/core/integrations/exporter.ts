/** Interop export/import and generated-agent-file rendering. */
import path from 'node:path';
import { GENERATED_HEADER, VERSION } from '../runtime/constants.js';
import type { MemoryEntry } from '../runtime/types.js';
import { readText, writeJson, writeText } from '../system/fsx.js';
import { loadConfig } from '../runtime/config.js';
import { readGuardedMemory } from '../safety/safe-read.js';

const formats = new Set(['agents-md', 'claude-md', 'cursor-rules']);
/** E15: deprecated export names accepted for one release. */
const FORMAT_ALIASES: Record<string, string> = { cursorrules: 'cursor-rules' };
const GENERATED_PREFIX = '<!-- Auto-generated by engram v';
const CURSOR_EXPORT_DESCRIPTION = 'Engram project memory: team rules and knowledge for this repository. Apply when work touches project conventions.';

/** Canonical export format; `warn` receives a deprecation note for an alias (CLI flags only, K9). */
export function normalizeFormat(format: string, warn?: (note: string) => void): string {
  const canonical = Object.hasOwn(FORMAT_ALIASES, format) ? FORMAT_ALIASES[format] : undefined;
  if (!canonical) return format;
  warn?.(`${format} is deprecated; use --format ${canonical}`);
  return canonical;
}

/** A generated sync target: the Engram header first, or right after `.mdc` frontmatter; any version. */
function isGeneratedSyncFile(text: string): boolean {
  if (text.startsWith(GENERATED_PREFIX)) return true;
  const fm = text.match(/^---\r?\n[\s\S]*?\r?\n---\r?\n/);
  return Boolean(fm) && text.slice(fm![0].length).startsWith(GENERATED_PREFIX);
}

/** Render memory into common agent instruction formats. */
export async function renderFormat(cwd: string, entries: MemoryEntry[], requested: string): Promise<string> {
  const format = normalizeFormat(requested);
  assertFormat(format);
  const config = await loadConfig(cwd);
  const chunks = [GENERATED_HEADER, '# Engram Memory Export'];
  for (const entry of entries) {
    const row = await readGuardedMemory(cwd, entry, config);
    if (row.flagged) chunks.push(`\n<!-- skipped ${entry.scope}:${entry.file}: ${row.flagged} -->`);
    else chunks.push(`\n<!-- ${entry.scope}:${entry.file} -->\n${row.content.trim()}`);
  }
  if (format === 'cursor-rules') {
    const body = chunks.join('\n\n').replace(/^# Engram Memory Export/m, '# Cursor Rules');
    return `---\ndescription: ${JSON.stringify(CURSOR_EXPORT_DESCRIPTION)}\nalwaysApply: false\n---\n${body}`;
  }
  if (format === 'claude-md') return chunks.join('\n\n').replace(/^# Engram Memory Export/m, '# CLAUDE.md');
  return chunks.join('\n\n').replace(/^# Engram Memory Export/m, '# AGENTS.md');
}

/** Export a deterministic JSON bundle; returns the entries written (flagged memories are skipped). */
export async function exportBundle(cwd: string, entries: MemoryEntry[], outFile: string): Promise<MemoryEntry[]> {
  const config = await loadConfig(cwd);
  const memories = [];
  for (const entry of entries) {
    const row = await readGuardedMemory(cwd, entry, config, { render: false });
    if (!row.flagged) memories.push({ entry, content: row.content });
  }
  await writeJson(outFile, { version: VERSION, exported_at: new Date().toISOString(), memories });
  return memories.map((item) => item.entry);
}

/** Write live-sync targets without touching non-generated files. */
export async function writeSyncTarget(cwd: string, requested: string, content: string): Promise<string> {
  const format = normalizeFormat(requested);
  assertFormat(format);
  const target = format === 'claude-md' ? 'CLAUDE.md' : format === 'agents-md' ? 'AGENTS.md' : path.join('.cursor', 'rules', 'engram.mdc');
  const full = path.join(cwd, target);
  const current = await readText(full);
  if (current && !isGeneratedSyncFile(current)) throw new Error(`Refusing to overwrite non-generated ${target}`);
  await writeText(full, content);
  return target.replace(/\\/g, '/');
}

export function assertFormat(format: string): void {
  if (!formats.has(normalizeFormat(format))) throw new Error(`unsupported export format: ${format}`);
}
