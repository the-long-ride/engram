function agentSkill(name: string, description: string, body: string, extra: { whenToUse?: string; userInvocable?: boolean } = {}): string {
  const lines = ['---', `name: ${name}`, `description: ${yamlString(description)}`];
  if (extra.whenToUse) lines.push(`when_to_use: ${yamlString(extra.whenToUse)}`);
  if (extra.userInvocable !== undefined) lines.push(`user-invocable: ${extra.userInvocable}`);
  return `${lines.join('\n')}\n---\n${body}`;
}

export type SkillHost = 'claude' | 'spec';
export type SkillIssue = { field: string; message: string };

/** Agent Skills spec fields; Claude Code also accepts its documented extensions. */
const SPEC_SKILL_FIELDS = new Set(['name', 'description', 'license', 'compatibility', 'metadata', 'allowed-tools']);
const CLAUDE_SKILL_FIELDS = new Set([...SPEC_SKILL_FIELDS, 'when_to_use', 'user-invocable', 'disable-model-invocation', 'argument-hint', 'arguments', 'disallowed-tools', 'model', 'effort', 'context', 'agent', 'background', 'hooks', 'paths', 'shell']);
const SKILL_NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
export const SKILL_NAME_MAX = 64;
export const SKILL_DESCRIPTION_MAX = 1024;
export const SKILL_COMPATIBILITY_MAX = 500;
export const CLAUDE_LISTING_MAX = 1536;

/** Validate SKILL.md frontmatter (agentskills.io/specification; code.claude.com/docs/en/skills); `dirName` is the parent folder. */
export function validateSkillFrontmatter(host: SkillHost, fm: Record<string, unknown>, dirName: string): SkillIssue[] {
  const issues: SkillIssue[] = [];
  const add = (field: string, message: string): void => { issues.push({ field, message }); };
  const { name, description, compatibility, metadata } = fm;
  if (typeof name !== 'string' || !name) add('name', 'is required');
  else if (name.length > SKILL_NAME_MAX) add('name', `is longer than ${SKILL_NAME_MAX} characters`);
  else if (!SKILL_NAME.test(name)) add('name', 'must be lowercase letters, digits, and single hyphens, not starting or ending with a hyphen');
  else if (name !== dirName) add('name', `must equal the directory name "${dirName}"`);
  if (typeof description !== 'string' || !description.trim()) add('description', 'is required');
  else if (description.length > SKILL_DESCRIPTION_MAX) add('description', `is longer than ${SKILL_DESCRIPTION_MAX} characters`);
  if (compatibility !== undefined && (typeof compatibility !== 'string' || !compatibility || compatibility.length > SKILL_COMPATIBILITY_MAX)) add('compatibility', `must be 1-${SKILL_COMPATIBILITY_MAX} characters`);
  if (metadata !== undefined && !(isPlainObject(metadata) && Object.values(metadata).every((value) => typeof value === 'string'))) add('metadata', 'must be a map of strings');
  if (fm['allowed-tools'] !== undefined && typeof fm['allowed-tools'] !== 'string') add('allowed-tools', 'must be a space-separated string');
  const allowed = host === 'claude' ? CLAUDE_SKILL_FIELDS : SPEC_SKILL_FIELDS;
  for (const key of Object.keys(fm)) if (!allowed.has(key)) add(key, 'not allowed outside Claude Code');
  if (host === 'claude') {
    const listing = (typeof description === 'string' ? description.length : 0) + (typeof fm.when_to_use === 'string' ? fm.when_to_use.length : 0);
    if (listing > CLAUDE_LISTING_MAX) add('when_to_use', `description plus when_to_use is over ${CLAUDE_LISTING_MAX} characters`);
    for (const key of ['user-invocable', 'disable-model-invocation']) if (fm[key] !== undefined && typeof fm[key] !== 'boolean') add(key, 'must be a boolean');
  }
  return issues;
}

/** Validate a raw SKILL.md: frontmatter must start on line 1; the parent directory of `file` is the expected skill name. */
export function validateSkillFile(host: SkillHost, raw: string, file: string): SkillIssue[] {
  if (!/^---\r?\n/.test(raw)) return [{ field: 'frontmatter', message: 'must start on line 1' }];
  let data: Record<string, unknown>;
  try {
    const parsed = parseFrontmatter(raw);
    if (!parsed.rawBlock) return [{ field: 'frontmatter', message: 'is not closed with ---' }];
    data = parsed.data;
  } catch (error) {
    return [{ field: 'frontmatter', message: error instanceof Error ? error.message : String(error) }];
  }
  const parts = file.replace(/\\/g, '/').split('/');
  return validateSkillFrontmatter(host, data, parts[parts.length - 2] ?? '');
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function yamlString(value: string): string {
  return JSON.stringify(value);
}

