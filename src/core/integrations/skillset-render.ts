/** Upsert a workspace managed block into existing content. Replaces legacy generated full content. */
export function upsertWorkspaceManagedBlock(existing: string, block: string): { text: string; action: InstallAction } {
  const wrappedBlock = block;
  if (!existing.trim()) return { text: `${wrappedBlock}\n`, action: 'written' };
  // If file is fully generated legacy content (has HEADER + compact body), replace with only block
  if ((existing.includes(HEADER) || existing.includes(LINE_HEADER)) &&
      (existing.includes('Save flow:') || existing.includes('Rule memories:') || existing.includes('Default agent mode: compact') || existing.includes('Runtime Bootstrap'))) {
    return { text: `${wrappedBlock}\n`, action: 'written' };
  }
  // Otherwise upsert block in human-authored content
  if (hasWorkspaceManagedBlock(existing)) {
    const pattern = new RegExp(`${escapeRegExp(WORKSPACE_BEGIN)}[\\s\\S]*?${escapeRegExp(WORKSPACE_END)}`, 'g');
    const humanContent = existing.replace(pattern, '').trimEnd();
    return { text: `${humanContent ? `${humanContent}\n\n` : ''}${wrappedBlock}\n`, action: 'updated' };
  }
  const humanContent = existing.trimEnd();
  return { text: `${humanContent ? `${humanContent}\n\n` : ''}${wrappedBlock}\n`, action: 'updated' };
}

/** Remove the workspace managed block from content. */
export function removeWorkspaceManagedBlock(content: string): string {
  const pattern = new RegExp(`${escapeRegExp(WORKSPACE_BEGIN)}[\\s\\S]*?${escapeRegExp(WORKSPACE_END)}`, 'g');
  return content.replace(pattern, '').replace(/\n{3,}/g, '\n\n');
}

/** Check if content has a workspace managed block. */
export function hasWorkspaceManagedBlock(content: string): boolean {
  return content.includes(WORKSPACE_BEGIN) && content.includes(WORKSPACE_END);
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function skillsetMarkdown(title: string, readMode = 'auto', profile: InstructionProfile = 'compact', hooks = false): string {
  return `${HEADER}

# ${title}

${instructionBody(readMode, profile, hooks)}
`;
}

function instructionBody(readMode: string, profile: InstructionProfile, hooks: HookMode = false): string {
  return profile === 'bootstrap'
    ? bootstrapSkillInstructions(readMode)
    : compactSkillInstructions(readMode, hooks);
}

